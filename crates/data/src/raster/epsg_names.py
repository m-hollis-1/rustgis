"""Regenerates `epsg_names.rs`: the names of the EPSG and ESRI coordinate systems RustGIS knows.

Usage (pyproj installed, from the repository root):

    python crates/data/src/raster/epsg_names.py > crates/data/src/raster/epsg_names.rs

and update nothing by hand: the PROJ, EPSG dataset and pyproj versions are in the header the
script prints. Use a PROJ at least as new as the one `esri.rs` and `epsg_gap.rs` record, or the
newest codes of those tables come out without a name (the check is the `every_known_code_has_a_name`
test in `crs.rs`).

The rows: every EPSG projected, geographic, geocentric and compound coordinate system of the database,
deprecated ones included (RustGIS's tables have them), but not the vertical ones, which none holds; and the ESRI projected and
geographic 2D ones, deprecated included. Sorted by code, for a binary search.
"""

import sys

import pyproj
from pyproj.database import get_database_metadata, query_crs_info
from pyproj.enums import PJType

sys.stdout.reconfigure(encoding="utf-8", newline="\n")


def rows(auth, types):
    infos = query_crs_info(auth_name=auth, allow_deprecated=True)
    names = {int(i.code): i.name for i in infos if i.type in types}
    out = []
    for code in sorted(names):
        name = names[code].replace("\\", "\\\\").replace('"', '\\"')
        out.append(f'    ({code}, "{name}"),')
    return out


EPSG_TYPES = {
    PJType.PROJECTED_CRS,
    PJType.GEOGRAPHIC_2D_CRS,
    PJType.GEOGRAPHIC_3D_CRS,
    PJType.GEOCENTRIC_CRS,
    PJType.COMPOUND_CRS,
    PJType.CRS,
}
epsg = rows("EPSG", EPSG_TYPES)
esri = rows("ESRI", {PJType.PROJECTED_CRS, PJType.GEOGRAPHIC_2D_CRS})

print(f"""//! Names of the EPSG and ESRI coordinate systems, for `epsg_name` and `esri_name` in `crs.rs`:
//! `NAD83 / Texas Central (ftUS)` for EPSG:2277, which a layout prints for its map's `{{crsName}}`.
//! The EPSG names are the dataset's own; the ESRI ones are the names PROJ's database holds for
//! Esri's systems (`NAD_1983_StatePlane_Texas_Central_FIPS_4203_Feet`), not the spellings ArcGIS
//! Pro shows.
//!
//! Generated by `epsg_names.py` (next to this file) from PROJ {pyproj.proj_version_str}'s database (EPSG dataset
//! {get_database_metadata('EPSG.VERSION')}, {get_database_metadata('EPSG.DATE')}) with pyproj {pyproj.__version__}: {len(epsg)} EPSG and {len(esri)} ESRI names.

#[rustfmt::skip]
pub(crate) const EPSG_NAMES: &[(u32, &str)] = &[""")
print("\n".join(epsg))
print("];\n\n#[rustfmt::skip]\npub(crate) const ESRI_NAMES: &[(u32, &str)] = &[")
print("\n".join(esri))
print("];")
